#!/usr/bin/env node
/**
 * build-selector-index.mjs — index every selector literal in the source.
 *
 * The DOM picker (entrypoints/picker.content) uses this to answer "which
 * extension code already targets the element I just clicked?". Without it the
 * picker can only check utils/selectors.ts, and most selectors are still inline
 * literals spread across ~30 feature files.
 *
 * Regenerate after moving selectors around:
 *   yarn picker:index
 *
 * Output is committed so the picker works without a build step. It carries a
 * timestamp; the picker warns when the index is older than the newest source
 * file it indexed.
 */

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "utils", "selector-index.generated.ts");
const SCAN_DIRS = [ "entrypoints", "utils", "components", "composables" ];

/** Functions whose string arguments are CSS selectors. */
const SELECTOR_FNS = [
  "querySelector",
  "querySelectorAll",
  "waitForElement",
  "waitForElementWithTextContent",
  "closest",
  "matches",
];

// picker.content is the tool doing the lookup — indexing its own selectors just
// makes it report itself as "code targeting this element".
const SKIP_DIRS = new Set([ "node_modules", ".output", ".wxt", "dist", ".git", "picker.content" ]);

function walk(dir, out = []) {
  let entries;
  try { entries = readdirSync(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    if (SKIP_DIRS.has(e.name)) continue;
    const full = join(dir, e.name);
    if (e.isDirectory()) walk(full, out);
    else if (/\.(ts|vue)$/.test(e.name) && !e.name.endsWith(".generated.ts")) out.push(full);
  }
  return out;
}

/**
 * Pull selector literals out of one file.
 *
 * Handles the two shapes used in this codebase:
 *   querySelector("sel")
 *   waitForElement([ "sel-a", "sel-b" ])
 *
 * Template literals containing ${...} are skipped: they are not statically
 * known, so they cannot be matched against a live element anyway.
 */
function extract(file) {
  const src = readFileSync(file, "utf8");
  const lines = src.split("\n");
  const rel = relative(ROOT, file);
  const found = [];

  const fnAlt = SELECTOR_FNS.join("|");
  // fn( ... ) capturing everything up to the closing paren on the same line.
  const callRe = new RegExp(`\\.?\\b(${fnAlt})\\s*\\(([^)]*)\\)`, "g");
  // Any quoted string inside that argument list.
  const strRe = /(["'`])((?:\\.|(?!\1)[^\\])*)\1/g;

  lines.forEach((line, i) => {
    for (const call of line.matchAll(callRe)) {
      const [ , fn, args ] = call;
      for (const s of args.matchAll(strRe)) {
        const value = s[2];
        if (!value || value.includes("${")) continue;
        // Filter out obvious non-selectors (event names, keys, plain words used
        // as arguments to matches()/closest() in unrelated contexts).
        if (!/[.#[\]>:\s-]/.test(value) && !/^[a-z]+$/i.test(value)) continue;
        found.push({ selector: value, file: rel, line: i + 1, fn });
      }
    }
  });

  return found;
}

const files = SCAN_DIRS.flatMap(d => walk(join(ROOT, d)));
const usages = files.flatMap(extract);

// Newest mtime across scanned files, so the picker can flag a stale index.
const newestSource = files.reduce((max, f) => {
  const m = statSync(f).mtimeMs;
  return m > max ? m : max;
}, 0);

// Deduplicate identical (selector, file, line) triples.
const seen = new Set();
const unique = usages.filter((u) => {
  const k = `${u.selector}::${u.file}::${u.line}`;
  if (seen.has(k)) return false;
  seen.add(k);
  return true;
});
unique.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);

const banner = `// AUTO-GENERATED by scripts/build-selector-index.mjs — do not edit by hand.
// Regenerate with: yarn picker:index
//
// Consumed by the dev-only DOM picker to report which extension code already
// targets a picked element. Not referenced by any shipped feature.
`;

const body = `${banner}
export interface SelectorUsage {
  /** The literal as written in source. */
  selector: string;
  /** Repo-relative path. */
  file: string;
  line: number;
  /** Which function it was passed to. */
  fn: string;
}

/** When this index was generated (ms since epoch). */
export const GENERATED_AT = ${Date.now()};

/** Newest mtime among the source files scanned, for staleness detection. */
export const NEWEST_SOURCE_AT = ${Math.round(newestSource)};

export const SELECTOR_USAGES: SelectorUsage[] = ${JSON.stringify(unique, null, 2)};
`;

writeFileSync(OUT, body);

const byFile = new Set(unique.map(u => u.file));
console.log(`Indexed ${unique.length} selector literals across ${byFile.size} files.`);
console.log(`Scanned ${files.length} source files in: ${SCAN_DIRS.join(", ")}`);
console.log(`Wrote ${relative(ROOT, OUT)}`);
